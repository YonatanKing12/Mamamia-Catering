/**
 * שורת המכסה. מוחזרת כטקסט לצורך `aria-live` בלבד — התצוגה החזותית
 * מרכיבה את אותה שורה עם `<Num>` סביב כל ספרה.
 *
 * «נבחרו 5 מתוך 7» — שתי הספרות מופרדות במילה עברית, ולכן אין כאן
 * מקף בין רצפי ספרות ואין היפוך.
 */
export function quotaSentence(chosen: number, included: number): string {
  return `נבחרו ${chosen} מתוך ${included}`;
}

/** «אפשר לבחור עוד 2 בלי תוספת» — עידוד, לא שגיאה. */
export function remainingSentence(remaining: number): string {
  if (remaining <= 0) return "";
  return remaining === 1 ? "אפשר לבחור עוד מנה אחת" : `אפשר לבחור עוד ${remaining} מנות`;
}

/** «‎3 מנות נבחרו» לשורה המכווצת של הסיכום. */
export function pickedSentence(count: number): string {
  if (count === 0) return COPY.summaryEmpty;
  return count === 1 ? "מנה אחת נבחרה" : `${count} מנות נבחרו`;
}

/** «‎80 סועדים». משמש בהודעת הוואטסאפ ובשורה המכווצת. */
export function guestsSentence(guests: number): string {
  return guests === 1 ? "סועד אחד" : `${guests} סועדים`;
}
