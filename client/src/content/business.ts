/** ערך שטרם סופק. `null` הוא המצב התקין, לא באג. */
export type Slot<T> = T | null;

/** שער טיפוסים: מצמצם Slot<T> ל־T ומאפשר תנאי רינדור בטוח. */
export const filled = <T,>(v: Slot<T>): v is T =>
  v !== null && v !== undefined && v !== "";

