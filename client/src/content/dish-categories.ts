/**
 * ═══════════════════════════════════════════════════════════════════════
 *  קטגוריות המגדיר — קבוצות הבחירה, המכסות, ושכבת השדות שהמגדיר מוסיף למנה.
 * ═══════════════════════════════════════════════════════════════════════
 *
 * ‎spec: 04 §6 (מודל בונה התפריט). המנוע שנמדד באתר הייחוס הוא «מוצר עם
 * קבוצות אפשרויות, מכסת בחירה לכל קבוצה, ותוספת מחיר לאפשרות». הקובץ הזה
 * הוא הקבוצות והמכסות; `content/packages.ts` הוא החבילה, הבחירה והתמחור.
 *
 * ─────────────────────────────────────────────────────────────────────
 *  היחס ל־`content/dishes.ts` — הרחבה, לא שכפול
 * ─────────────────────────────────────────────────────────────────────
 * ‎`content/dishes.ts` נשאר **מקור האמת היחיד למנה**: שם, תיאור, מדור,
 * זמינות לקייטרינג, באילו מסעדות היא מוגשת, סימוני תזונה, קישור לתפריט
 * החי. אין כאן טיפוס מנה מתחרה, אין רשימת מנות שנייה, ואין שדה שמשוכפל.
 *
 * מה שכן נוסף כאן הן שלוש עובדות שקיימות **רק בהקשר המגדיר**:
 *
 *   · `category` — לאיזו קבוצת בחירה המנה שייכת. זה **אינו** ‎`dish.course`:
 *     ‎`course` הוא סדר ההגשה בתפריט («פסטות», «קינוחים»), והקטגוריה היא
 *     קבוצת בחירה מסחרית («שבעה סלטים כלולים»). לרוב הן יתלכדו, ולפעמים
 *     לא — «סלטים» היא קטגוריה ולא מדור, ומדור «עיקריות» יכול להתפצל
 *     לשתי קטגוריות עם מכסות שונות. שני מודלים נפרדים, בכוונה.
 *   · `surcharge` — תוספת מחיר לסועד. ‎`Slot`, כלומר `null` = לא נמסר.
 *   · `image` — נתיב לתמונה מקומית. ‎`Slot`.
 *
 * הן יושבות ב־`DISH_EXTRAS`, מפה לפי מזהה מנה, ומצטרפות למנה בזמן ריצה.
 * מנה בלי רשומה כאן פשוט אינה חלק מהמגדיר — היא עדיין מנה תקינה לגמרי
 * בכל שאר האתר. זו הסיבה שההרחבה היא מפה נפרדת ולא שדות אופציונליים על
 * ‎`Dish`: המגדיר הוא צרכן אחד מיני רבים, ואסור לו להכתיב את המודל.
 *
 * ─────────────────────────────────────────────────────────────────────
 *  החוק — זהה לזה של `dishes.ts`
 * ─────────────────────────────────────────────────────────────────────
 * הנתונים ריקים, וזה המצב התקין להיום. כל עזר כאן מחזיר `[]`, `null` או
 * ‎`false` במצב הריק, תמיד. אין קטגוריית דמו, אין «7 סלטים» לדוגמה בקוד,
 * ואין שלד אפור. קטגוריה בלי מנות אינה מרונדרת; מגדיר בלי קטגוריות אינו
 * מרונדר כלל (‎04 §6: «מגדיר תפריט ריק הוא מסך לבן»).
 *
 * ─────────────────────────────────────────────────────────────────────
 *  כסף
 * ─────────────────────────────────────────────────────────────────────
 * כל סכום בקובץ הזה ובקובץ החבילות הוא **שקלים שלמים, לסועד אחד**.
 * ‎`null` פירושו «לא נמסר» — ולעולם לא «אפס». מנה כלולה במחיר הבסיס היא
 * ‎`surcharge: 0` במפורש. ההבחנה הזאת היא כל ההגנה: `0` נכנס לחשבון,
 * ‎`null` מאפס את כל התמחור ל־`null` (ראו `priceSelection()` בחבילות).
 *
 * ─────────────────────────────────────────────────────────────────────
 *  RTL — למה אין כאן בוני משפטים
 * ─────────────────────────────────────────────────────────────────────
 * הקובץ מחזיר **מספרים ומבנים**, לא מחרוזות כמו «בחרו 7 מנות». ספרה בתוך
 * משפט עברי חייבת לעבור דרך `<Num>` בקומפוננטה, ומחרוזת שנבנתה כאן אינה
 * יכולה לשאת קומפוננטה. הרכבת המשפט היא עבודת התצוגה, וזו לא גחמה —
 * משפט שנבנה כאן יגיע ל־DOM עם ספרה חשופה ויתהפך.
 */

