/* ═══════════════════ אוצר מילים ═══════════════════ */

/**
 * slug לטיני יציב, כמו `DishId` ו־`MenuId`. מימד אנליטיקה ושדה על שורת
 * הליד — שינוי שלו מנתק היסטוריה. שינוי השם העברי מותר ורצוי בכל רגע.
 */
export type CategoryId = string;

/**
 * מדיניות חריגה מהמכסה.
 *
 * איחוד מובחן ולא שני שדות שטוחים, בכוונה: כשהחריגה אסורה **אין** שדה
 * תוספת מחיר לקרוא ממנו. זה חוסם מבנית את התקלה שבה קומפוננטה מציגה
 * «כל מנה נוספת בתוספת ₪X» בקטגוריה שבכלל לא מרשה מנה נוספת.
 *
 * ‎`surchargePerExtra` — שקלים לסועד, לכל מנה מעבר למכסה. `Slot`, ולכן
 * קטגוריה יכולה להיות מוגדרת כמרשה חריגה עוד לפני שנמסר כמה זה עולה;
 * במצב הזה התמחור כולו מחזיר `null` והמגדיר מציג בחירות בלי סכומים
 * (‎04 §6: «בלי מחירון מאושר המגדיר מציג בחירות בלי סכומים»).
 */
export type OverQuotaPolicy =
  | { allowed: false }
  | { allowed: true; surchargePerExtra: Slot<number> };

/* ═══════════════════ הרשומה — קטגוריה ═══════════════════ */

export interface DishCategory {
  /** slug יציב. לא לשנות אחרי שנקבע. */
  id: CategoryId;

  /** שם הקטגוריה בעברית, כלשון הלקוח. זו כותרת הצעד במגדיר. */
  nameHe: string;

  /**
   * הערת הנחיה קצרה מתחת לכותרת, או `null`. `null` הוא מצב תקין ונפוץ,
   * והשורה נשמטת לגמרי — לא נשארת שורה ריקה שתופסת גובה.
   *
   * אין לכתוב כאן את המכסה («בחרו 7»): המכסה היא מספר, והיא מורכבת
   * למשפט בקומפוננטה דרך `<Num>`. ראו בלוק ה־RTL בראש הקובץ.
   */
  noteHe: string | null;

  /**
   * כמה מנות כלולות במחיר הבסיס. ‎0 הוא ערך תקין ומשמעותי: קטגוריה
   * שכולה בתוספת תשלום.
   *
   * זו ברירת המחדל של הקטגוריה. חבילה רשאית לדרוס אותה
   * (‎`PackageCategory.includedQuota` ב־`content/packages.ts`) — וזה
   * המנגנון שבו «חבילה מורחבת» מקבלת תשע במקום שבע. הפונקציה היחידה
   * שיודעת להכריע בין השניים היא `quotaFor()`, שם.
   */
  includedQuota: number;

  /**
   * תקרה קשיחה למספר הבחירות בקטגוריה, כולל החריגות בתשלום.
   * ‎`null` = לא נמסרה תקרה.
   *
   * ‎`null` **אינו** «בלי הגבלה» כשהחריגה אסורה — במקרה הזה התקרה
   * האפקטיבית היא המכסה עצמה. ההכרעה יושבת ב־`maxFor()` בקובץ החבילות,
   * ואין לשכפל אותה בקומפוננטה.
   */
  max: number | null;

  /**
   * האם חייבים לבחור בקטגוריה כדי להשלים את ההזמנה. קטגוריית חובה עם
   * מכסה ‎0 היא סתירה, ו־`validateDishCategories()` מתריעה עליה.
   */
  required: boolean;

  overQuota: OverQuotaPolicy;

  /** הערה למפתח. אינה מרונדרת לעולם. */
  note?: string;
}

/* ═══════════════════ הרשומה — שכבת המגדיר על המנה ═══════════════════ */

export interface DishExtra {
  /** לאיזו קבוצת בחירה המנה שייכת. חייבת להתקיים ב־`DISH_CATEGORIES`. */
  category: CategoryId;

  /**
   * תוספת מחיר לסועד, בשקלים שלמים.
   *
   *   ‎`0`    — כלולה במחיר הבסיס. **הצהרה מפורשת**, ונדרשת.
   *   ‎`> 0`  — בתוספת תשלום, גם בתוך המכסה.
   *   ‎`null` — לא נמסר. המנה עדיין נבחרת ונשלחת בליד; פשוט אין סכום,
   *            ולכן `priceSelection()` מחזיר `null` לכל ההזמנה.
   *
   * ‎`null` אינו `0`. מנה שהוזנה בלי מחיר ותתומחר כאפס היא מנה שנמכרה
   * בחינם באתר ותחויב בטלפון — וזו בדיוק הטעיה שהמנעולים נועדו למנוע.
   */
  surcharge: Slot<number>;

  /**
   * נתיב לתמונה מקומית תחת `/images/dishes/…` — נתיב, לא URL חיצוני.
   * ‎`null` ⇒ הכרטיס מרונדר **בלי מסגרת תמונה**: לא ריבוע אפור, לא
   * ‎placeholder, לא אייקון צלחת. כרטיס בלי תמונה הוא כרטיס טקסט מלא
   * ברוחב הכרטיס, ולא כרטיס עם חור.
   *
   * הפלטה של ‎04 §2 כהה, ולכן תמונה נדרשת עם רקע נקי או חתוכה; זו הערה
   * להפקה, לא כלל קוד.
   */
  image: Slot<string>;
}

/**
 * המנה כפי שהמגדיר רואה אותה: כל שדות `Dish` ועוד שלושת שדות המגדיר.
 * טיפוס נגזר — אין כאן ממשק שני שצריך לתחזק במקביל.
 */
export type ConfiguratorDish = Dish & DishExtra;

/* ═══════════════════ הנתונים ═══════════════════ */

/**
 * ריק, וזה המצב התקין להיום.
 *
 * ─────────────────────────────────────────────────────────────────────
 *  מה הלקוח צריך למסור — קטגוריות
 * ─────────────────────────────────────────────────────────────────────
 * שורה לכל קבוצת בחירה במגדיר:
 *
 *   1. **שם הקטגוריה** — כלשונו. «סלטים», «מנות פתיחה», «עיקריות».
 *   2. **כמה כלולות במחיר הבסיס** — מספר. זה ה«שבעה סלטים».
 *   3. **תקרה** — הכי הרבה שאפשר לבחור בקטגוריה, או «אין תקרה».
 *   4. **חובה או רשות** — האם אפשר לסגור הזמנה בלי לבחור כאן כלום.
 *   5. **מותר לחרוג בתשלום?** — כן / לא. אם כן: **כמה עולה כל מנה
 *      נוספת, לסועד**. «כן» בלי סכום הוא מצב תקין ומתועד — הבחירה
 *      תעבוד, המחירים פשוט לא יוצגו לאיש.
 *
 * המזהים (`id`) אינם עבודה של הלקוח — מי שמזין קובע slug לטיני קצר ויציב.
 *
 * ─────────────────────────────────────────────────────────────────────
 *  דוגמה — **בהערה בלבד. לעולם לא בתוך `DISH_CATEGORIES`.**
 * ─────────────────────────────────────────────────────────────────────
 * ```ts
 * {
 *   id: "salads",
 *   nameHe: "סלטים",
 *   noteHe: null,
 *   includedQuota: 7,
 *   max: 12,
 *   required: true,
 *   overQuota: { allowed: true, surchargePerExtra: null },
 * }
 * ```
 * ‎`surchargePerExtra: null` בדוגמה הוא לא פספוס — זה בדיוק המצב שבו
 * הקטגוריה מוגדרת והמחיר עוד לא אושר.
 */
export const DISH_CATEGORIES: readonly DishCategory[] = [];

/**
 * ריק, וזה המצב התקין להיום.
 *
 * ─────────────────────────────────────────────────────────────────────
 *  מה הלקוח צריך למסור — לכל מנה
 * ─────────────────────────────────────────────────────────────────────
 * שלוש עמודות נוספות על הטבלה שכבר מתוארת בראש `content/dishes.ts`:
 *
 *   1. **קטגוריה במגדיר** — אחת מהקטגוריות למעלה.
 *   2. **תוספת מחיר לסועד** — ‎0 לכלולה, מספר לתוספת, ריק ל«עוד לא נקבע».
 *   3. **תמונה** — קובץ. בלי תמונה זה תקין; הכרטיס מרונדר בלי מסגרת.
 *
 * המפתח הוא ה־`id` של המנה מ־`DISHES`. מפתח שאין לו מנה מתאימה, או מנה
 * שאינה זמינה לקייטרינג, נשמט בשקט — ראו `CONFIGURATOR_DISHES`.
 *
 * ─────────────────────────────────────────────────────────────────────
 *  דוגמה — **בהערה בלבד.**
 * ─────────────────────────────────────────────────────────────────────
 * ```ts
 * {
 *"tagliatelle-ragu": { category: "mains", surcharge: 0,    image: "/images/dishes/tagliatelle-ragu.webp" },
 *"carpaccio":        { category: "starters", surcharge: 12, image: null },
 * }
 * ```
 */
export const DISH_EXTRAS: Readonly<Record<DishId, DishExtra>> = {};

/* ═══════════════════ החיבור ═══════════════════ */

const CATEGORY_IDS = new Set<string>(DISH_CATEGORIES.map((c) => c.id));

/**
 * המנות שהמגדיר עובד מולן: מנות שעברו את שער התצוגה של `dishes.ts`
 * **וגם** קיבלו שכבת מגדיר תקינה, עם קטגוריה שבאמת קיימת.
 *
 * שלוש הסיבות להשמטה שקטה, וכולן אותה סיבה: קלט ידני.
 *   · אין רשומה ב־`DISH_EXTRAS` — המנה לא שויכה לקבוצת בחירה.
 *   · הקטגוריה לא קיימת — שגיאת הקלדה בגיליון.
 *   · המנה אינה זמינה לקייטרינג — נחסמה כבר ב־`dishes.ts`.
 *
 * ‎`validateDishCategories()` מתריעה על שתי הראשונות בפיתוח, כדי
 * שההשמטה לא תהיה שקטה גם למי שמזין.
 */
export const CONFIGURATOR_DISHES: readonly ConfiguratorDish[] = CATERING_DISHES.flatMap(
  (dish) => {
    const extra = DISH_EXTRAS[dish.id];
    if (!extra) return [];
    if (!CATEGORY_IDS.has(extra.category)) return [];
    return [{ ...dish, ...extra }];
  },
);

/* ═══════════════════ שליפה ═══════════════════ */

/** קטגוריה לפי מזהה. לא נמצאה — `null`. */
export function categoryById(id: CategoryId): DishCategory | null {
  return DISH_CATEGORIES.find((c) => c.id === id) ?? null;
}

/**
 * המנות בקטגוריה, בסדר שבו נמסרו ב־`DISHES`.
 *
 * זו הפונקציה שצעד במגדיר בנוי עליה. `[]` ⇒ **הצעד אינו קיים**: אין
 * כותרת, אין מסגרת, ואין «בקרוב». קטגוריה בלי מנות היא קטגוריה שהלקוח
 * טרם מילא, ומסך ריק עם כותרת הוא בדיוק מה ש־04 §6 אוסר.
 *
 * מקבל מזהה או את הרשומה עצמה, כמו `dishesForMenu()`.
 */
export function dishesForCategory(category: CategoryId | DishCategory): ConfiguratorDish[] {
  const id = typeof category === "string" ? category : category.id;
  return CONFIGURATOR_DISHES.filter((d) => d.category === id);
}

/** האם לקטגוריה יש בכלל מה להראות. השער של כל צעד במגדיר. */
export function hasCategoryDishes(category: CategoryId | DishCategory): boolean {
  return dishesForCategory(category).length > 0;
}

/**
 * הקטגוריות שמותר לרנדר: אלה שנותרה בהן ולו מנה אחת.
 * ‎`DISH_CATEGORIES` הגולמי מיועד לכלים ולוולידציה בלבד.
 */
export function renderableCategories(): DishCategory[] {
  return DISH_CATEGORIES.filter(hasCategoryDishes);
}

/**
 * האם יש בכלל מגדיר. השורה הראשונה בכל קומפוננטת מגדיר:
 *
 *   `if (!hasConfigurator()) return null;`
 *
 * היום `false`, ולכן המגדיר מחווט במלואו ואינו מרונדר בשום עמוד.
 */
export function hasConfigurator(): boolean {
  return CONFIGURATOR_DISHES.length > 0 && renderableCategories().length > 0;
}

/** מנת מגדיר לפי מזהה, מבין אלה שעברו את השער. לא נמצאה — `null`. */
export function configuratorDishById(id: DishId): ConfiguratorDish | null {
  return CONFIGURATOR_DISHES.find((d) => d.id === id) ?? null;
}

/* ═══════════════════ הצגה ═══════════════════ */

/**
 * הנתיב לתמונת המנה, ורק כשיש נתיב מקומי אמיתי. אין ⇒ `null`, והכרטיס
 * מרונדר בלי מסגרת תמונה כלל. אין ברירת מחדל ואין תמונה גנרית.
 */
export function imageFor(dish: ConfiguratorDish): Slot<string> {
  const src = dish.image;
  if (!src || !src.startsWith("/")) return null;
  return src;
}

/**
 * התוספת של מנה, כשהיא ידועה ושונה מאפס — כלומר כשיש בכלל מה להציג ליד
 * שם המנה. ‎`0` מחזיר `null` בכוונה: «בתוספת ₪0» הוא רעש.
 * ‎`null` מחזיר `null` — לא נמסר, אין תג.
 *
 * הערך מוחזר כמספר, לעטיפה ב־`<Money>` בקומפוננטה.
 *
 * ⚠ מספר שחוזר מכאן אינו רשות לרנדר. שער התצוגה של מחירים הוא
 * ‎`priceSelection()` ב־`content/packages.ts`, שדורש גם מחירון מאושר,
 * הכרעת מע״מ ונוסח סייג — בדיוק כמו `resolveEstimate()`
 * ב־`components/quote/estimate.tsx`. קומפוננטה שמציגה תוספת למנה בלי
 * שההזמנה כולה עברה את השער הזה מציגה מספר בלי הסייג שלו.
 */
export function visibleSurcharge(dish: ConfiguratorDish): Slot<number> {
  const s = dish.surcharge;
  if (typeof s !== "number" || !Number.isFinite(s) || s <= 0) return null;
  return s;
}

/* ═══════════════════ בדיקת שפיות ═══════════════════ */

/**
 * מאתרת את הטעויות שקורות כשמזינים גיליון ידנית. מוחזרת כרשימת מחרוזות
 * ולא זורקת — קובץ נתונים שגוי אסור לו להפיל עמוד ללקוח.
 */
export function validateDishCategories(
  categories: readonly DishCategory[] = DISH_CATEGORIES,
  extras: Readonly<Record<DishId, DishExtra>> = DISH_EXTRAS,
): string[] {
  const problems: string[] = [];
  const seen = new Set<CategoryId>();
  const ids = new Set<string>(categories.map((c) => c.id));

  for (const cat of categories) {
    const at = `category "${cat.id || "(ללא מזהה)"}"`;

    if (!cat.id) problems.push(`${at}: חסר מזהה`);
    else if (seen.has(cat.id)) problems.push(`${at}: מזהה כפול`);
    else seen.add(cat.id);

    if (!cat.nameHe?.trim()) problems.push(`${at}: חסר שם`);

    if (!Number.isInteger(cat.includedQuota) || cat.includedQuota < 0) {
      problems.push(`${at}: מכסה חייבת להיות מספר שלם אי־שלילי`);
    }

    if (cat.max !== null) {
      if (!Number.isInteger(cat.max) || cat.max < 1) {
        problems.push(`${at}: תקרה חייבת להיות מספר שלם חיובי או null`);
      } else if (cat.max < cat.includedQuota) {
        problems.push(`${at}: תקרה ${cat.max} קטנה מהמכסה ${cat.includedQuota}`);
      }
    }

    /* קטגוריית חובה שלא כלולה בה אף מנה ואי אפשר לחרוג בה — מבוי סתום:
       אי אפשר להשלים את ההזמנה בשום מסלול. */
    if (cat.required && cat.includedQuota === 0 && !cat.overQuota.allowed) {
      problems.push(`${at}: חובה, מכסה 0, וחריגה אסורה — אין דרך להשלים בחירה`);
    }

    if (cat.overQuota.allowed) {
      const extra = cat.overQuota.surchargePerExtra;
      if (extra !== null && (!Number.isFinite(extra) || extra <= 0)) {
        problems.push(`${at}: תוספת חריגה חייבת להיות חיובית או null`);
      }
      if (cat.max !== null && cat.max === cat.includedQuota) {
        problems.push(`${at}: חריגה מותרת אך התקרה שווה למכסה — החריגה לא אפשרית בפועל`);
      }
    }

    if (/₪|\bש"?ח\b|\d/.test(cat.noteHe ?? "")) {
      problems.push(`${at}: ספרה או מחיר בהערת הקטגוריה. מספרים מורכבים בקומפוננטה דרך <Num>`);
    }
  }

  for (const [dishId, extra] of Object.entries(extras)) {
    const at = `dish extra "${dishId}"`;

    if (!ids.has(extra.category)) {
      problems.push(`${at}: קטגוריה לא מוכרת "${extra.category}"`);
    }

    const dish = CATERING_DISHES.find((d) => d.id === dishId);
    if (!dish) {
      problems.push(`${at}: אין מנה זמינה לקייטרינג עם המזהה הזה — הרשומה תושמט`);
    } else if (!isCateringDish(dish)) {
      problems.push(`${at}: המנה אינה עוברת את שער הזמינות — הרשומה תושמט`);
    }

    if (extra.surcharge !== null) {
      if (!Number.isFinite(extra.surcharge) || extra.surcharge < 0) {
        problems.push(`${at}: תוספת מחיר חייבת להיות אי־שלילית או null`);
      }
    }

    if (extra.image !== null && !extra.image.startsWith("/")) {
      problems.push(`${at}: נתיב תמונה חייב להיות מקומי ולהתחיל ב־"/"`);
    }
  }

  return problems;
}

/* אזהרה בפיתוח בלבד. בפרודקשן אין לוג ואין השפעה על הרינדור. */
if (import.meta.env?.DEV) {
  const problems = validateDishCategories();
  if (problems.length > 0) {
    console.warn(`[dish-categories.ts] ${problems.length} בעיות:\n · ${problems.join("\n · ")}`);
  }
}
