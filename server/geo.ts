/** כתובת מוחלטת אם ה־origin ידוע; אחרת נתיב יחסי — לעולם לא דומיין מומצא. */
const url = (path: string, origin: string): string => (origin ? `${origin}${path}` : path);

const link = (entry: PageEntry, origin: string): string =>
  entry.he
